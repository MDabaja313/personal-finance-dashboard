for (const [slug, contributions] of Object.entries(goalContributionSeeds)) {
  const sum = contributions.reduce((acc, c) => acc + c.amountCents, 0);
  const fixture = mockGoals.find((g) => g.id === slug);
  if (!fixture) throw new Error(`no fixture goal for seed mapping ${slug}`);
  if (sum !== fixture.savedCents) {
    throw new Error(
      `goal_contributions for ${slug} sum to ${sum}, expected fixture savedCents ${fixture.savedCents}`
    );
  }
}

