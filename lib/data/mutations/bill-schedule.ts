import "server-only";

import { mapWriteError } from "@/lib/data/db-errors";
import { getDataClient, getOwnerId } from "@/lib/data/supabase";
import { isAppError } from "@/lib/errors";

/**
 * The rolling occurrence horizon, kept up to date after a write that could
 * have moved it.
 *
 * The bill counterpart of `lib/data/mutations/snapshots.ts`, and deliberately
 * the same shape: one RPC, no table access of any kind, and a best-effort
 * wrapper for use *after* a primary write has already committed.
 * `bill_occurrences` has no INSERT or DELETE grant for `authenticated` and
 * never will — occurrences are generated by
 * `private.generate_bill_occurrences_for_bill`, reachable only through the
 * `SECURITY DEFINER` bridge `public.maintain_bill_schedule`, which this module
 * is the only thing in the codebase to name.
 *
 * ## What the bridge can and cannot be asked
 *
 * It takes an owned bill id and one boolean. It takes no owner (that comes
 * from the request's own JWT claim inside the database), no horizon, no date
 * range and no month — so a caller cannot choose how far ahead to generate,
 * cannot address another owner, and cannot reach a bill that is not theirs.
 * It can never touch a paid or skipped occurrence: the writer's DELETE policy
 * is restricted to `status = 'scheduled'` and to the calling request's own
 * rows, and Phase 4's `guard_bill_occurrence_delete()` refuses the rest
 * regardless.
 *
 * ## Why bill create and edit do *not* come through here
 *
 * They call the bridge inside their own RPC, in the same transaction as the
 * bill write, because a bill and its schedule must commit together — a created
 * bill with no occurrence is invisible on `/bills` and on the dashboard, and
 * an edited bill whose future schedule failed to rebuild would disagree with
 * its own terms permanently. See `lib/data/mutations/bills.ts`.
 *
 * This module exists for the writes where that is *not* true: an occurrence
 * status change. Marking a bill paid does not change the schedule; it just
 * happens to be the moment worth topping the horizon up, since it is what an
 * owner does regularly as time passes. PostgREST issues one statement per
 * request in its own transaction, so this is unavoidably a second request —
 * and, exactly as with the snapshot refresh, the right way for it to fail is
 * quietly:
 *
 * - **The status change is the primary fact.** It has already committed. The
 *   occurrence is paid, the history is correct, and `/bills` renders it.
 * - **The horizon is maintenance.** A bill that did not gain its next row this
 *   time gains it on the next status change, the next edit, or the next
 *   unarchive — the generator recomputes from the bill's current terms rather
 *   than applying a delta, so nothing accumulates.
 *
 * Reporting a committed "marked paid" as failed because a scheduled row for
 * next year was not generated would be a lie that invites the person to click
 * again.
 *
 * ## What may be logged
 *
 * A sanitized operation noun and a classification code — the identical rule
 * `snapshots.ts` states. Never an amount, a date, a bill id, an owner id, a
 * row, or a raw PostgREST payload. The `AppError`'s own `message` is not
 * logged either: it may name a relation, and its `cause` carries the driver's
 * response verbatim.
 */

/** The one RPC this module may call. */
const MAINTAIN_RPC = "maintain_bill_schedule";

/**
 * Brings one owned bill's future schedule up to the rolling horizon.
 *
 * `rebuildFuture` is always `false` from this module: nothing that calls it
 * changed the bill's terms, so there is nothing to rebuild — only to top up.
 * The rebuilding path belongs to `public.replace_bill`, which is the only
 * thing that knows the terms actually moved.
 *
 * Throws on failure, like every other function in this layer. The best-effort
 * behavior lives in `maintainBillScheduleAfter` below, so the swallowing is
 * visible at the call site rather than hidden in here.
 *
 * `getOwnerId()` is called first, per this layer's unconditional rule, so an
 * ended session fails as `unauthorized` here rather than as an opaque database
 * refusal.
 */
export async function maintainBillSchedule(billId: string): Promise<void> {
  await getOwnerId();

  const supabase = await getDataClient();

  const { error } = await supabase.rpc(MAINTAIN_RPC, {
    p_bill_id: billId,
    p_rebuild_future: false,
  });

  if (error) throw mapWriteError(error, "the bill schedule");
}

/**
 * The best-effort form, for use immediately after a write that has already
 * committed.
 *
 * Awaited rather than fired and forgotten, for the reason
 * `refreshCurrentSnapshotAfter` gives: an un-awaited promise in a Server
 * Action can outlive the request, and a rejection from one is an unhandled
 * rejection rather than a log line. Awaiting also means the schedule the
 * re-render reads is already current by the time the action revalidates.
 *
 * `operation` is a short developer-authored noun for the write that preceded
 * this one ("the bill") — never user input and never row data.
 */
export async function maintainBillScheduleAfter(
  billId: string,
  operation: string
): Promise<void> {
  try {
    await maintainBillSchedule(billId);
  } catch (error) {
    // Classification only. See "What may be logged" above.
    const code = isAppError(error) ? error.code : "unknown";
    console.error(
      `bill schedule maintenance failed after saving ${operation} [${code}]. ` +
        `The write itself succeeded; the rolling occurrence horizon is short until the next one.`
    );
  }
}
