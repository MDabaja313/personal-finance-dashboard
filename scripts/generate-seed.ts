/**
 * Generates supabase/seed.sql from the existing lib/mock/** fixtures.
 *
 * The seed reproduces the current mock-backed application exactly — it
 * inserts literal, deterministic rows only. It never calls
 * generate_bill_occurrences, write_net_worth_snapshot, or
 * write_net_worth_snapshots_for_range: those Phase 4 functions are
 * proven separately, against their own dedicated pgTAP test data, not
 * against this seed.
 *
 * Regenerating this file from an unchanged lib/mock/** must produce no
 * diff — every id, timestamp, and computed value here is a pure
 * function of the fixture data, never of the current wall-clock time or
 * of randomness.
 *
 * Run: npm run seed:generate
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
